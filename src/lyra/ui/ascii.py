@lru_cache(maxsize=256)
def render_ascii(text: str, width: int, height: int) -> str:
    """Keep original spelling if a whole word cannot fit or a glyph is unavailable."""
    text = text.upper()
    if not text or height < 5 or any(letter not in PATTERNS for letter in text):
        return text
    glyphs = [PATTERNS[letter].split("/") for letter in text]
    required = sum(len(glyph[0]) for glyph in glyphs) + len(glyphs) - 1
    if required > width:
        return text
    rows = [" ".join(glyph[row] for glyph in glyphs) for row in range(5)]
    return "\n".join(row.replace("1", "#").replace("0", " ") for row in rows)


def is_art(text: str) -> bool:
    return "\n" in text and max(map(cell_len, text.splitlines()), default=0) > 0
